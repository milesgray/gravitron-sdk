def test_estimate_tokens():
    # 1. Empty strings
    est_empty = estimate_tokens("", "")
    assert est_empty.prompt_tokens == 0
    assert est_empty.completion_tokens == 0
    assert est_empty.total_tokens == 0

    # 2. Prompt only
    prompt = "Hello world, this is a test prompt."
    est_prompt = estimate_tokens(prompt_text=prompt)
    assert est_prompt.prompt_tokens > 0
    assert est_prompt.completion_tokens == 0
    assert est_prompt.total_tokens == est_prompt.prompt_tokens

    # 3. Prompt and completion
    resp = "This is a response generated by the model."
    est_both = estimate_tokens(prompt_text=prompt, response_text=resp)
    assert est_both.prompt_tokens > 0
    assert est_both.completion_tokens > 0
    assert est_both.total_tokens == est_both.prompt_tokens + est_both.completion_tokens

    # 4. Tool calls add overhead
    tools = [
        {"tool_name": "run_command", "tool_args": {"command": "ls -la"}},
        {"tool_name": "view_file", "tool_args": {"path": "/tmp/test"}},
    ]
    est_tools = estimate_tokens(prompt_text=prompt, response_text=resp, tool_calls=tools)
    assert est_tools.completion_tokens > est_both.completion_tokens
    assert est_tools.completion_tokens >= est_both.completion_tokens + (2 * 45)


def test_telemetry_storage_crud_and_aggregations(tmp_path):
    db_file = tmp_path / "telemetry_test.db"
    storage = TelemetryStorage(db_path=db_file)

    now = time.time()
    # Record events for two plugins
    ev1 = TelemetryEvent(
        plugin_slug="plan-orchestrator",
        agent_id="planner-agent",
        conversation_id="conv-101",
        turn_number=1,
        prompt_tokens_est=100,
        completion_tokens_est=50,
        total_tokens_est=150,
        tool_calls_count=2,
        duration_ms=450.0,
        status=TelemetryEventStatus.SUCCESS,
        timestamp=now - 10,
    )
    ev2 = TelemetryEvent(
        plugin_slug="plan-orchestrator",
        agent_id="planner-agent",
        conversation_id="conv-101",
        turn_number=2,
        prompt_tokens_est=200,
        completion_tokens_est=100,
        total_tokens_est=300,
        tool_calls_count=1,
        duration_ms=650.0,
        status=TelemetryEventStatus.SUCCESS,
        timestamp=now - 5,
    )
    ev3 = TelemetryEvent(
        plugin_slug="architect",
        agent_id="critic-agent",
        conversation_id="conv-202",
        turn_number=1,
        prompt_tokens_est=500,
        completion_tokens_est=250,
        total_tokens_est=750,
        tool_calls_count=0,
        duration_ms=1200.0,
        status=TelemetryEventStatus.SUCCESS,
        timestamp=now,
    )

    storage.record_event(ev1)
    storage.record_event(ev2)
    storage.record_event(ev3)

    # Test global summary
    global_sum = storage.get_global_summary()
    assert global_sum.total_calls_all_time == 3
    assert global_sum.total_tokens_all_time == 1200
    assert len(global_sum.plugin_summaries) == 2

    # Verify per-plugin rollup inside global summary
    plan_orch = next(p for p in global_sum.plugin_summaries if p.plugin_slug == "plan-orchestrator")
    assert plan_orch.total_tokens_est == 450
    assert plan_orch.total_calls == 2
    assert plan_orch.tool_calls_count == 3

    # Test plugin quota summary
    plugin_sum = storage.get_plugin_quota_summary("plan-orchestrator", window_minutes=60)
    assert plugin_sum.plugin_slug == "plan-orchestrator"
    assert plugin_sum.total_tokens_est == 450
    assert plugin_sum.total_calls == 2
    assert plugin_sum.tokens_per_minute > 0
    assert len(plugin_sum.agents) == 1
    assert plugin_sum.agents[0].agent_id == "planner-agent"
    assert plugin_sum.agents[0].total_tokens_est == 450

    # Test granular metric time series
    metrics = storage.get_granular_metrics(plugin_slug="plan-orchestrator", window_minutes=60)
    assert len(metrics) > 0
    total_tokens_in_metrics = sum(m.tokens_per_minute for m in metrics)
    assert total_tokens_in_metrics == 450


def test_agent_history_manager(tmp_path):
    history_dir = tmp_path / "history"
    mgr = AgentHistoryManager(base_dir=history_dir)

    conv_id = "test-conv-001"
    slug = "plugin-sample"
    agent = "worker-1"

    tools = [
        {"name": "list_files", "arguments": {"dir": "/src"}, "output": "file1.py\nfile2.py"}
    ]

    turn1 = mgr.record_turn(
        conversation_id=conv_id,
        plugin_slug=slug,
        agent_id=agent,
        source="user",
        content="List files please",
        tool_calls=tools,
        tokens_est=65,
        duration_ms=300.0,
    )

    assert turn1.agent_id == agent
    assert len(turn1.tool_calls) == 1
    assert turn1.tool_calls[0].name == "list_files"

    turn2 = mgr.record_turn(
        conversation_id=conv_id,
        plugin_slug=slug,
        agent_id=agent,
        source="model",
        content="Here are the files: file1.py, file2.py",
        tokens_est=25,
        duration_ms=120.0,
    )

    # Query by conversation
    session = mgr.get_history(conv_id)
    assert session is not None
    assert session.conversation_id == conv_id
    assert len(session.turns) == 2
    assert session.turns[0].content == "List files please"
    assert session.turns[1].content == "Here are the files: file1.py, file2.py"

    # Query by agent
    agent_turns = mgr.get_agent_history(slug, agent)
    assert len(agent_turns) == 2
    assert agent_turns[0].content == "List files please"
    assert agent_turns[1].content == "Here are the files: file1.py, file2.py"
